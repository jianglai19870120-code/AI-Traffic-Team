def normalize_step_signal(text: str) -> str:
    cleaned = plain_title(text, "执行卡点")
    cleaned = re.sub(r"^(怎么|如何|为何|为什么){2,}", "怎么", cleaned)
    cleaned = re.sub(r"^(怎么|如何)(怎么|如何)", r"\1", cleaned)
    cleaned = re.sub(r"^怎么怎么", "怎么", cleaned)
    cleaned = re.sub(r"^如何怎么", "如何", cleaned)
    return cleaned.strip("。！？!? ")


def is_complete_question(text: str) -> bool:
    return text.endswith(("？", "?"))


def format_step_title(signal: str) -> str:
    title = normalize_step_signal(signal)
    if not title:
        return "执行卡点怎么拆开？"
    if is_complete_question(title):
        return title
    if "什么时候" in title or "为何" in title or "为什么" in title or "还是" in title or "什么" in title or title.startswith("怎样"):
        return title + "？"
    if title.startswith(("从", "用", "先", "让", "把")):
        return title + "怎么做？"
    if "怎么" in title or "如何" in title:
        return title + "？"
    if title.endswith(("动作", "路径", "方法", "节奏", "结构")):
        return title + "该怎么搭？"
    return title + "怎么做？"


def fallback_quote_from_signal(signal: str) -> str:
    quote = signal.strip("。！？!? ")
    quote = quote.replace("却", "，").replace("还以为", "别再以为")
    if quote.startswith("把"):
        quote = "别" + quote
    compact = quote.strip("。！？!? ")
    if compact.endswith("了"):
        quote = compact[:-1] + "才对"
    elif compact.endswith("的"):
        quote = compact + "更值钱"
    elif compact.endswith(("和", "与", "及")):
        quote = compact + "更重要"
    if not quote.endswith(("。", "！", "？")):
        quote += "。"
    return quote


def fallback_quote_from_step_signal(signal: str) -> str:
    quote = signal.strip("。！？!? ")
    if "该怎么" in quote:
        left, right = quote.split("该怎么", 1)
        right = right.strip()
        if right.startswith("先"):
            quote = f"{left}，{right}"
        else:
            quote = f"{left}，先{right}"
    elif quote.startswith("怎么"):
        quote = "先" + quote[2:]
    compact = quote.strip("。！？!? ")
    if compact.endswith("了"):
        quote = compact[:-1] + "才行"
    elif compact.endswith("的"):
        quote = compact + "更稳"
    elif compact.endswith(("和", "与", "及")):
        quote = compact + "更重要"
    if not quote.endswith(("。", "！", "？")):
        quote += "。"
    return quote


def resolve_topic_fallback(title: str) -> dict[str, object] | None:
    exact = TITLE_TOPIC_FALLBACKS.get(title)
    if exact:
        return exact
    for item in TITLE_FAMILY_FALLBACKS:
        if any(keyword in title for keyword in item["keywords"]):
            return item
    return None


def build_title_fallback_quotes(title: str) -> list[str]:
    fallback = resolve_topic_fallback(title)
    if not fallback:
        return []
    quotes: list[str] = []
    for signal in fallback["mistakes"]:
        quote = fallback_quote_from_signal(signal)
        if any(word in quote for word in QUOTE_ISSUE_WORDS) or any(word in quote for word in SOURCE_WORDS):
            continue
        if han_len(quote) < 4:
            continue
        quotes.append(quote)
        if len(quotes) >= 10:
            break
    for signal in fallback["steps"]:
        if len(quotes) >= 10:
            break
        quote = fallback_quote_from_step_signal(signal)
        if any(word in quote for word in QUOTE_ISSUE_WORDS) or any(word in quote for word in SOURCE_WORDS):
            continue
        if han_len(quote) < 4:
            continue
        quotes.append(quote)
    return quotes


def apply_title_topic_fallback(title: str, mistakes: list[dict[str, str]], steps: list[dict[str, str]]) -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    fallback = resolve_topic_fallback(title)
    if not fallback:
        return mistakes, steps
    existing_mistakes = {item["signal"] for item in mistakes}
    existing_steps = {item["signal"] for item in steps}
    summary = fallback["summary"]
    for signal in fallback["mistakes"]:
        if signal not in existing_mistakes:
            mistakes.append({"kind": "mistake", "label": signal, "signal": signal, "source_summary": summary})
    for signal in fallback["steps"]:
        if signal not in existing_steps:
            steps.append({"kind": "step", "label": signal, "signal": signal, "source_summary": summary})
    mistakes = dedupe_candidates(mistakes, "signal", 16)
    steps = dedupe_candidates(steps, "signal", 12)
    return mistakes, steps


